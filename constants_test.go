package pcre2_test

import (
	"testing"

	"github.com/go-regexp/pcre2"
	"github.com/go-regexp/pcre2/internal/pcre2testgo"
	"github.com/go-regexp/pcre2/internal/pcre2testgo/mods"
)

// The harness keeps its own copies of the pcre2.h values it needs (the
// modifier tables must not depend on the library). They must agree with the
// library's constants.
func TestHarnessConstantsMatchLibrary(t *testing.T) {
	pairs := []struct {
		name      string
		got, want uint32
	}{
		{"ANCHORED", mods.ANCHORED, pcre2.PCRE2_ANCHORED},
		{"NO_UTF_CHECK", mods.NO_UTF_CHECK, pcre2.PCRE2_NO_UTF_CHECK},
		{"ENDANCHORED", mods.ENDANCHORED, pcre2.PCRE2_ENDANCHORED},
		{"ALLOW_EMPTY_CLASS", mods.ALLOW_EMPTY_CLASS, pcre2.PCRE2_ALLOW_EMPTY_CLASS},
		{"ALT_BSUX", mods.ALT_BSUX, pcre2.PCRE2_ALT_BSUX},
		{"AUTO_CALLOUT", mods.AUTO_CALLOUT, pcre2.PCRE2_AUTO_CALLOUT},
		{"CASELESS", mods.CASELESS, pcre2.PCRE2_CASELESS},
		{"DOLLAR_ENDONLY", mods.DOLLAR_ENDONLY, pcre2.PCRE2_DOLLAR_ENDONLY},
		{"DOTALL", mods.DOTALL, pcre2.PCRE2_DOTALL},
		{"DUPNAMES", mods.DUPNAMES, pcre2.PCRE2_DUPNAMES},
		{"EXTENDED", mods.EXTENDED, pcre2.PCRE2_EXTENDED},
		{"FIRSTLINE", mods.FIRSTLINE, pcre2.PCRE2_FIRSTLINE},
		{"MATCH_UNSET_BACKREF", mods.MATCH_UNSET_BACKREF, pcre2.PCRE2_MATCH_UNSET_BACKREF},
		{"MULTILINE", mods.MULTILINE, pcre2.PCRE2_MULTILINE},
		{"NEVER_UCP", mods.NEVER_UCP, pcre2.PCRE2_NEVER_UCP},
		{"NEVER_UTF", mods.NEVER_UTF, pcre2.PCRE2_NEVER_UTF},
		{"NO_AUTO_CAPTURE", mods.NO_AUTO_CAPTURE, pcre2.PCRE2_NO_AUTO_CAPTURE},
		{"NO_AUTO_POSSESS", mods.NO_AUTO_POSSESS, pcre2.PCRE2_NO_AUTO_POSSESS},
		{"NO_DOTSTAR_ANCHOR", mods.NO_DOTSTAR_ANCHOR, pcre2.PCRE2_NO_DOTSTAR_ANCHOR},
		{"NO_START_OPTIMIZE", mods.NO_START_OPTIMIZE, pcre2.PCRE2_NO_START_OPTIMIZE},
		{"UCP", mods.UCP, pcre2.PCRE2_UCP},
		{"UNGREEDY", mods.UNGREEDY, pcre2.PCRE2_UNGREEDY},
		{"UTF", mods.UTF, pcre2.PCRE2_UTF},
		{"NEVER_BACKSLASH_C", mods.NEVER_BACKSLASH_C, pcre2.PCRE2_NEVER_BACKSLASH_C},
		{"ALT_CIRCUMFLEX", mods.ALT_CIRCUMFLEX, pcre2.PCRE2_ALT_CIRCUMFLEX},
		{"ALT_VERBNAMES", mods.ALT_VERBNAMES, pcre2.PCRE2_ALT_VERBNAMES},
		{"USE_OFFSET_LIMIT", mods.USE_OFFSET_LIMIT, pcre2.PCRE2_USE_OFFSET_LIMIT},
		{"EXTENDED_MORE", mods.EXTENDED_MORE, pcre2.PCRE2_EXTENDED_MORE},
		{"LITERAL", mods.LITERAL, pcre2.PCRE2_LITERAL},
		{"MATCH_INVALID_UTF", mods.MATCH_INVALID_UTF, pcre2.PCRE2_MATCH_INVALID_UTF},
		{"NOTBOL", mods.NOTBOL, pcre2.PCRE2_NOTBOL},
		{"NOTEOL", mods.NOTEOL, pcre2.PCRE2_NOTEOL},
		{"NOTEMPTY", mods.NOTEMPTY, pcre2.PCRE2_NOTEMPTY},
		{"NOTEMPTY_ATSTART", mods.NOTEMPTY_ATSTART, pcre2.PCRE2_NOTEMPTY_ATSTART},
		{"PARTIAL_SOFT", mods.PARTIAL_SOFT, pcre2.PCRE2_PARTIAL_SOFT},
		{"PARTIAL_HARD", mods.PARTIAL_HARD, pcre2.PCRE2_PARTIAL_HARD},
		{"DFA_RESTART", mods.DFA_RESTART, pcre2.PCRE2_DFA_RESTART},
		{"DFA_SHORTEST", mods.DFA_SHORTEST, pcre2.PCRE2_DFA_SHORTEST},
		{"NO_JIT", mods.NO_JIT, pcre2.PCRE2_NO_JIT},
		{"COPY_MATCHED_SUBJECT", mods.COPY_MATCHED_SUBJECT, pcre2.PCRE2_COPY_MATCHED_SUBJECT},
		{"DISABLE_RECURSELOOP_CHECK", mods.DISABLE_RECURSELOOP_CHK, pcre2.PCRE2_DISABLE_RECURSELOOP_CHECK},
		{"EXTRA_ALLOW_SURROGATE_ESCAPES", mods.EXTRA_ALLOW_SURROGATE_ESCAPES, pcre2.PCRE2_EXTRA_ALLOW_SURROGATE_ESCAPES},
		{"EXTRA_BAD_ESCAPE_IS_LITERAL", mods.EXTRA_BAD_ESCAPE_IS_LITERAL, pcre2.PCRE2_EXTRA_BAD_ESCAPE_IS_LITERAL},
		{"EXTRA_MATCH_WORD", mods.EXTRA_MATCH_WORD, pcre2.PCRE2_EXTRA_MATCH_WORD},
		{"EXTRA_MATCH_LINE", mods.EXTRA_MATCH_LINE, pcre2.PCRE2_EXTRA_MATCH_LINE},
		{"EXTRA_ESCAPED_CR_IS_LF", mods.EXTRA_ESCAPED_CR_IS_LF, pcre2.PCRE2_EXTRA_ESCAPED_CR_IS_LF},
		{"EXTRA_ALT_BSUX", mods.EXTRA_ALT_BSUX, pcre2.PCRE2_EXTRA_ALT_BSUX},
		{"EXTRA_ALLOW_LOOKAROUND_BSK", mods.EXTRA_ALLOW_LOOKAROUND_BSK, pcre2.PCRE2_EXTRA_ALLOW_LOOKAROUND_BSK},
		{"EXTRA_CASELESS_RESTRICT", mods.EXTRA_CASELESS_RESTRICT, pcre2.PCRE2_EXTRA_CASELESS_RESTRICT},
		{"EXTRA_ASCII_BSD", mods.EXTRA_ASCII_BSD, pcre2.PCRE2_EXTRA_ASCII_BSD},
		{"EXTRA_ASCII_BSS", mods.EXTRA_ASCII_BSS, pcre2.PCRE2_EXTRA_ASCII_BSS},
		{"EXTRA_ASCII_BSW", mods.EXTRA_ASCII_BSW, pcre2.PCRE2_EXTRA_ASCII_BSW},
		{"EXTRA_ASCII_POSIX", mods.EXTRA_ASCII_POSIX, pcre2.PCRE2_EXTRA_ASCII_POSIX},
		{"EXTRA_ASCII_DIGIT", mods.EXTRA_ASCII_DIGIT, pcre2.PCRE2_EXTRA_ASCII_DIGIT},
		{"CONVERT_UTF", mods.CONVERT_UTF, pcre2.PCRE2_CONVERT_UTF},
		{"CONVERT_NO_UTF_CHECK", mods.CONVERT_NO_UTF_CHECK, pcre2.PCRE2_CONVERT_NO_UTF_CHECK},
		{"CONVERT_POSIX_BASIC", mods.CONVERT_POSIX_BASIC, pcre2.PCRE2_CONVERT_POSIX_BASIC},
		{"CONVERT_POSIX_EXTENDED", mods.CONVERT_POSIX_EXTENDED, pcre2.PCRE2_CONVERT_POSIX_EXTENDED},
		{"CONVERT_GLOB", mods.CONVERT_GLOB, pcre2.PCRE2_CONVERT_GLOB},
		{"CONVERT_GLOB_NO_WILD_SEPARATOR", mods.CONVERT_GLOB_NO_WILD_SEPARATOR, pcre2.PCRE2_CONVERT_GLOB_NO_WILD_SEPARATOR},
		{"CONVERT_GLOB_NO_STARSTAR", mods.CONVERT_GLOB_NO_STARSTAR, pcre2.PCRE2_CONVERT_GLOB_NO_STARSTAR},
		{"NEWLINE_CR", mods.NEWLINE_CR, pcre2.PCRE2_NEWLINE_CR},
		{"NEWLINE_LF", mods.NEWLINE_LF, pcre2.PCRE2_NEWLINE_LF},
		{"NEWLINE_CRLF", mods.NEWLINE_CRLF, pcre2.PCRE2_NEWLINE_CRLF},
		{"NEWLINE_ANY", mods.NEWLINE_ANY, pcre2.PCRE2_NEWLINE_ANY},
		{"NEWLINE_ANYCRLF", mods.NEWLINE_ANYCRLF, pcre2.PCRE2_NEWLINE_ANYCRLF},
		{"NEWLINE_NUL", mods.NEWLINE_NUL, pcre2.PCRE2_NEWLINE_NUL},
		{"BSR_UNICODE", mods.BSR_UNICODE, pcre2.PCRE2_BSR_UNICODE},
		{"BSR_ANYCRLF", mods.BSR_ANYCRLF, pcre2.PCRE2_BSR_ANYCRLF},
		{"SubstituteGlobal", pcre2testgo.SubstituteGlobal, pcre2.PCRE2_SUBSTITUTE_GLOBAL},
		{"SubstituteExtended", pcre2testgo.SubstituteExtended, pcre2.PCRE2_SUBSTITUTE_EXTENDED},
		{"SubstituteUnsetEmpty", pcre2testgo.SubstituteUnsetEmpty, pcre2.PCRE2_SUBSTITUTE_UNSET_EMPTY},
		{"SubstituteUnknownUnset", pcre2testgo.SubstituteUnknownUnset, pcre2.PCRE2_SUBSTITUTE_UNKNOWN_UNSET},
		{"SubstituteOverflowLength", pcre2testgo.SubstituteOverflowLength, pcre2.PCRE2_SUBSTITUTE_OVERFLOW_LENGTH},
		{"SubstituteLiteral", pcre2testgo.SubstituteLiteral, pcre2.PCRE2_SUBSTITUTE_LITERAL},
		{"SubstituteMatched", pcre2testgo.SubstituteMatched, pcre2.PCRE2_SUBSTITUTE_MATCHED},
		{"SubstituteReplacementOnly", pcre2testgo.SubstituteReplacementOnly, pcre2.PCRE2_SUBSTITUTE_REPLACEMENT_ONLY},
	}
	for _, p := range pairs {
		if p.got != p.want {
			t.Errorf("%s: harness has %#x, library has %#x", p.name, p.got, p.want)
		}
	}
}
