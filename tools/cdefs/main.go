// Command cdefs turns the object-like #define lines and the enum blocks of
// PCRE2's C headers into Go constants, so that constants are never retyped by
// hand. It ports no C file by itself: it reads pcre2.h.generic,
// pcre2_internal.h, pcre2_intmodedep.h, pcre2_compile.c, pcre2_ucp.h and the
// build's config.h, whichever -src arguments name.
//
// Usage:
//
//	cdefs -out consts_gen.go -header "text" \
//	   -src dir/pcre2.h.generic:PCRE2_ \
//	   -src dir/pcre2_internal.h \
//	   -table dir/pcre2_internal.h:OP_LENGTHS=opLengths
//
// A -src argument is "path" or "path:PREFIX,PREFIX" (only names beginning with
// one of the prefixes are emitted; all names stay visible to the evaluator).
// A constant whose C text has a u-suffixed literal is emitted as a typed
// uint32 constant, every other one as an untyped constant.
// The module has no dependency, so the standard flag package is used rather
// than cobra; run is driven by tests.
package main

import (
	"flag"
	"fmt"
	"go/format"
	"io"
	"os"
	"regexp"
	"strconv"
	"strings"
)

type multi []string

func (m *multi) String() string     { return strings.Join(*m, ",") }
func (m *multi) Set(s string) error { *m = append(*m, s); return nil }

func main() { os.Exit(run(os.Args[1:], os.Stdout, os.Stderr)) }

// definition is one named C constant before evaluation.
type definition struct {
	name   string
	expr   string
	enum   bool // enum member: implicit value is previous+1
	prev   string
	order  int
	filter []string
	file   string
}

type evaluator struct {
	defs  map[string]*definition
	cache map[string]int64
	busy  map[string]bool
}

func run(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("cdefs", flag.ContinueOnError)
	fs.SetOutput(stderr)
	out := fs.String("out", "", "output Go file")
	pkg := fs.String("pkg", "pcre2", "package name")
	header := fs.String("header", "", "first comment line of the output")
	skip := fs.String("skip", "", "comma-separated names never emitted (hand-written elsewhere)")
	var srcs, tables multi
	fs.Var(&srcs, "src", "path[:PREFIX,PREFIX]")
	fs.Var(&tables, "table", "path:MACRO=goName")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	if *out == "" || len(srcs) == 0 {
		fmt.Fprintln(stderr, "cdefs: -out and at least one -src are required")
		return 2
	}
	ev := &evaluator{defs: map[string]*definition{}, cache: map[string]int64{}, busy: map[string]bool{}}
	var ordered []*definition
	order := 0
	var texts = map[string]string{}
	load := func(path string) (string, error) {
		if t, ok := texts[path]; ok {
			return t, nil
		}
		b, err := os.ReadFile(path)
		if err != nil {
			return "", err
		}
		t := preprocess(joinContinuations(stripComments(string(b))), stderr)
		texts[path] = t
		return t, nil
	}
	for _, s := range srcs {
		path, pre, _ := strings.Cut(s, ":")
		var filter []string
		if pre != "" {
			filter = strings.Split(pre, ",")
		}
		text, err := load(path)
		if err != nil {
			fmt.Fprintln(stderr, "cdefs:", err)
			return 1
		}
		for _, d := range scanDefines(text) {
			d.filter, d.file = filter, path
			if _, dup := ev.defs[d.name]; dup {
				continue
			}
			d.order = order
			order++
			ev.defs[d.name] = d
			ordered = append(ordered, d)
		}
	}
	var sb strings.Builder
	fmt.Fprintf(&sb, "// Code generated by tools/cdefs; DO NOT EDIT.\n// %s\n\npackage %s\n\n", *header, *pkg)
	skipped := 0
	emitted := 0
	skipSet := map[string]bool{}
	for _, n := range strings.Split(*skip, ",") {
		skipSet[n] = true
	}
	sb.WriteString("const (\n")
	for _, d := range ordered {
		if !matches(d) || skipSet[d.name] {
			continue
		}
		v, err := ev.eval(d.name)
		if err != nil {
			skipped++
			continue
		}
		emitted++
		if d.enum || !uSuffixed(d.expr) {
			fmt.Fprintf(&sb, "\t%s = %d\n", d.name, v)
		} else {
			fmt.Fprintf(&sb, "\t%s uint32 = %#x\n", d.name, uint32(v))
		}
	}
	sb.WriteString(")\n")
	for _, t := range tables {
		path, rest, _ := strings.Cut(t, ":")
		macro, goName, ok := strings.Cut(rest, "=")
		if !ok {
			fmt.Fprintln(stderr, "cdefs: bad -table", t)
			return 2
		}
		text, err := load(path)
		if err != nil {
			fmt.Fprintln(stderr, "cdefs:", err)
			return 1
		}
		body := macroBody(text, macro)
		if body == "" {
			fmt.Fprintf(stderr, "cdefs: macro %s not found in %s\n", macro, path)
			return 1
		}
		fmt.Fprintf(&sb, "\nvar %s = [...]uint8{\n", goName)
		for _, item := range strings.Split(body, ",") {
			v, err := ev.evalExpr(strings.TrimSpace(item))
			if err != nil {
				fmt.Fprintf(stderr, "cdefs: %s: %q: %v\n", macro, item, err)
				return 1
			}
			fmt.Fprintf(&sb, "\t%d,\n", v)
		}
		sb.WriteString("}\n")
	}
	formatted, ferr := format.Source([]byte(sb.String()))
	if ferr != nil {
		fmt.Fprintln(stderr, "cdefs: generated code does not parse:", ferr)
		return 1
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		fmt.Fprintln(stderr, "cdefs:", err)
		return 1
	}
	fmt.Fprintf(stdout, "cdefs: %d constants written to %s (%d not evaluable and skipped)\n", emitted, *out, skipped)
	return 0
}

func matches(d *definition) bool {
	if len(d.filter) == 0 {
		return true
	}
	for _, p := range d.filter {
		if strings.HasPrefix(d.name, p) {
			return true
		}
	}
	return false
}

var uLiteral = regexp.MustCompile(`\b(0[xX][0-9a-fA-F]+|[0-9]+)[uU]\b`)

func uSuffixed(expr string) bool { return uLiteral.MatchString(expr) }

var blockComment = regexp.MustCompile(`(?s)/\*.*?\*/`)
var lineComment = regexp.MustCompile(`//[^\n]*`)

// stripComments removes comments but keeps newlines so line structure holds.
func stripComments(s string) string {
	s = blockComment.ReplaceAllStringFunc(s, func(m string) string {
		return strings.Repeat("\n", strings.Count(m, "\n"))
	})
	return lineComment.ReplaceAllString(s, "")
}

func joinContinuations(s string) string {
	return strings.ReplaceAll(s, "\\\n", " ")
}

// builtDefined lists the symbols that are defined in the reference build
// (8-bit library, Unicode support, no JIT, LINK_SIZE 2).
var builtDefined = map[string]bool{
	"SUPPORT_UNICODE": true, "SUPPORT_PCRE2_8": true, "HAVE_MEMMOVE": true,
	"PCRE2_CODE_UNIT_WIDTH": true, "HAVE_CONFIG_H": true,
}

// trueConditions are the "#if" expressions that hold in that build. Any other
// "#if" expression is taken as false and reported on stderr.
var trueConditions = map[string]bool{
	"PCRE2_CODE_UNIT_WIDTH == 8": true,
	"LINK_SIZE == 2":             true,
	"defined PCRE2_CODE_UNIT_WIDTH && PCRE2_CODE_UNIT_WIDTH != 0": true,
}

var knownFalse = map[string]bool{
	"PCRE2_CODE_UNIT_WIDTH == 16": true, "PCRE2_CODE_UNIT_WIDTH == 32": true,
	"PCRE2_CODE_UNIT_WIDTH == 0": true, "LINK_SIZE == 3": true, "LINK_SIZE == 4": true,
	"defined EBCDIC && PCRE2_CODE_UNIT_WIDTH != 8": true,
	"PCRE2_CODE_UNIT_WIDTH == 8 || PCRE2_CODE_UNIT_WIDTH == 16 || PCRE2_CODE_UNIT_WIDTH == 32": false,
}

// preprocess keeps only the lines of the active conditional branches (the
// build described by builtDefined and trueConditions); blank lines replace
// the others so offsets stay meaningful. Unknown #if expressions go to warn.
func preprocess(text string, warn io.Writer) string {
	lines := strings.Split(text, "\n")
	type frame struct{ parentActive, taken, active bool }
	var stack []frame
	active := true
	defined := map[string]bool{}
	for k := range builtDefined {
		defined[k] = true
	}
	condRE := regexp.MustCompile(`^\s*#\s*(ifdef|ifndef|if|elif|else|endif)\b\s*(.*)$`)
	defRE := regexp.MustCompile(`^\s*#\s*define\s+([A-Za-z_][A-Za-z_0-9]*)`)
	undefRE := regexp.MustCompile(`^\s*#\s*undef\s+([A-Za-z_][A-Za-z_0-9]*)`)
	for i, ln := range lines {
		if m := condRE.FindStringSubmatch(ln); m != nil {
			kw, arg := m[1], strings.Join(strings.Fields(m[2]), " ")
			switch kw {
			case "ifdef", "ifndef", "if":
				var v bool
				switch kw {
				case "ifdef":
					v = defined[arg]
				case "ifndef":
					v = !defined[arg]
				default:
					v = trueConditions[arg]
					if !v && !knownFalse[arg] && active && warn != nil {
						fmt.Fprintf(warn, "cdefs: unknown #if %q taken as false\n", arg)
					}
				}
				stack = append(stack, frame{parentActive: active, taken: v, active: v})
				active = active && v
			case "elif":
				f := &stack[len(stack)-1]
				v := trueConditions[arg] && !f.taken
				f.taken = f.taken || v
				active = f.parentActive && v
			case "else":
				f := &stack[len(stack)-1]
				active = f.parentActive && !f.taken
				f.taken = true
			case "endif":
				active = stack[len(stack)-1].parentActive
				stack = stack[:len(stack)-1]
			}
			lines[i] = ""
			continue
		}
		if !active {
			lines[i] = ""
			continue
		}
		if m := defRE.FindStringSubmatch(ln); m != nil {
			defined[m[1]] = true
		} else if m := undefRE.FindStringSubmatch(ln); m != nil {
			delete(defined, m[1])
		}
	}
	return strings.Join(lines, "\n")
}

var defineRE = regexp.MustCompile(`(?m)^[ \t]*#[ \t]*define[ \t]+([A-Za-z_][A-Za-z_0-9]*)([^\n]*)$`)
var enumRE = regexp.MustCompile(`(?s)\benum\b[^{;]*\{([^}]*)\}`)

func scanDefines(text string) []*definition {
	type located struct {
		pos int
		d   *definition
	}
	var found []located
	for _, m := range defineRE.FindAllStringSubmatchIndex(text, -1) {
		name := text[m[2]:m[3]]
		rest := text[m[4]:m[5]]
		if strings.HasPrefix(rest, "(") { // function-like macro
			continue
		}
		rest = strings.TrimSpace(rest)
		if rest == "" {
			continue
		}
		found = append(found, located{m[0], &definition{name: name, expr: rest}})
	}
	for _, m := range enumRE.FindAllStringSubmatchIndex(text, -1) {
		body := text[m[2]:m[3]]
		prev := ""
		for _, item := range strings.Split(body, ",") {
			item = strings.TrimSpace(item)
			if item == "" {
				continue
			}
			name, expr, hasExpr := strings.Cut(item, "=")
			name = strings.TrimSpace(name)
			d := &definition{name: name, enum: true, prev: prev}
			if hasExpr {
				d.expr = strings.TrimSpace(expr)
			}
			found = append(found, located{m[0], d})
			prev = name
		}
	}
	// keep source order (defines and enums interleaved by position)
	for i := 1; i < len(found); i++ {
		for j := i; j > 0 && found[j].pos < found[j-1].pos; j-- {
			found[j], found[j-1] = found[j-1], found[j]
		}
	}
	res := make([]*definition, len(found))
	for i, f := range found {
		res[i] = f.d
	}
	return res
}

func macroBody(text, macro string) string {
	re := regexp.MustCompile(`(?m)^[ \t]*#[ \t]*define[ \t]+` + regexp.QuoteMeta(macro) + `[ \t]+([^\n]*)$`)
	m := re.FindStringSubmatch(text)
	if m == nil {
		return ""
	}
	return strings.TrimSpace(m[1])
}

func (e *evaluator) eval(name string) (int64, error) {
	if v, ok := e.cache[name]; ok {
		return v, nil
	}
	d, ok := e.defs[name]
	if !ok {
		return 0, fmt.Errorf("unknown identifier %s", name)
	}
	if e.busy[name] {
		return 0, fmt.Errorf("cycle at %s", name)
	}
	e.busy[name] = true
	defer delete(e.busy, name)
	var v int64
	var err error
	switch {
	case d.expr != "":
		v, err = e.evalExpr(d.expr)
	case d.enum && d.prev == "":
		v = 0
	case d.enum:
		var p int64
		p, err = e.eval(d.prev)
		v = p + 1
	}
	if err != nil {
		return 0, err
	}
	e.cache[name] = v
	return v, nil
}

// ---- expression evaluator ----

type parser struct {
	toks []string
	pos  int
	ev   *evaluator
}

var tokRE = regexp.MustCompile(`'(?:\\.[0-9a-fA-F]*|[^'\\])'|0[xX][0-9a-fA-F]+[uUlL]*|[0-9]+[uUlL]*|[A-Za-z_][A-Za-z_0-9]*|<<|>>|[-+*/|&^~()]`)

func (e *evaluator) evalExpr(s string) (int64, error) {
	s = strings.ReplaceAll(s, "sizeof(PCRE2_UCHAR)", "1")
	toks := tokRE.FindAllString(s, -1)
	if len(toks) == 0 {
		return 0, fmt.Errorf("empty expression %q", s)
	}
	// every character of s must be covered by a token (reject strings etc.)
	covered := 0
	for _, t := range toks {
		covered += len(t)
	}
	if covered != len(strings.Join(strings.Fields(s), "")) {
		return 0, fmt.Errorf("unsupported syntax in %q", s)
	}
	p := &parser{toks: toks, ev: e}
	v, err := p.or()
	if err != nil {
		return 0, err
	}
	if p.pos != len(p.toks) {
		return 0, fmt.Errorf("trailing tokens in %q", s)
	}
	return v, nil
}

func (p *parser) peek() string {
	if p.pos < len(p.toks) {
		return p.toks[p.pos]
	}
	return ""
}

func (p *parser) or() (int64, error) {
	l, err := p.xor()
	for err == nil && p.peek() == "|" {
		p.pos++
		var r int64
		if r, err = p.xor(); err == nil {
			l |= r
		}
	}
	return l, err
}

func (p *parser) xor() (int64, error) {
	l, err := p.and()
	for err == nil && p.peek() == "^" {
		p.pos++
		var r int64
		if r, err = p.and(); err == nil {
			l ^= r
		}
	}
	return l, err
}

func (p *parser) and() (int64, error) {
	l, err := p.shift()
	for err == nil && p.peek() == "&" {
		p.pos++
		var r int64
		if r, err = p.shift(); err == nil {
			l &= r
		}
	}
	return l, err
}

func (p *parser) shift() (int64, error) {
	l, err := p.add()
	for err == nil && (p.peek() == "<<" || p.peek() == ">>") {
		op := p.peek()
		p.pos++
		var r int64
		if r, err = p.add(); err == nil {
			if op == "<<" {
				l <<= uint(r)
			} else {
				l >>= uint(r)
			}
		}
	}
	return l, err
}

func (p *parser) add() (int64, error) {
	l, err := p.mul()
	for err == nil && (p.peek() == "+" || p.peek() == "-") {
		op := p.peek()
		p.pos++
		var r int64
		if r, err = p.mul(); err == nil {
			if op == "+" {
				l += r
			} else {
				l -= r
			}
		}
	}
	return l, err
}

func (p *parser) mul() (int64, error) {
	l, err := p.unary()
	for err == nil && (p.peek() == "*" || p.peek() == "/") {
		op := p.peek()
		p.pos++
		var r int64
		if r, err = p.unary(); err == nil {
			if op == "*" {
				l *= r
			} else if r == 0 {
				err = fmt.Errorf("division by zero")
			} else {
				l /= r
			}
		}
	}
	return l, err
}

var castWords = map[string]bool{"unsigned": true, "char": true, "int": true, "long": true,
	"uint8_t": true, "uint16_t": true, "uint32_t": true, "int32_t": true, "size_t": true, "PCRE2_SIZE": true}

func (p *parser) unary() (int64, error) {
	switch p.peek() {
	case "-":
		p.pos++
		v, err := p.unary()
		return -v, err
	case "~":
		p.pos++
		v, err := p.unary()
		return ^v, err
	case "(":
		// cast?
		j := p.pos + 1
		for j < len(p.toks) && castWords[p.toks[j]] {
			j++
		}
		if j > p.pos+1 && j < len(p.toks) && p.toks[j] == ")" {
			p.pos = j + 1
			return p.unary()
		}
		p.pos++
		v, err := p.or()
		if err != nil {
			return 0, err
		}
		if p.peek() != ")" {
			return 0, fmt.Errorf("missing )")
		}
		p.pos++
		return v, nil
	}
	return p.primary()
}

func (p *parser) primary() (int64, error) {
	t := p.peek()
	if t == "" {
		return 0, fmt.Errorf("unexpected end")
	}
	p.pos++
	switch {
	case t[0] == '\'':
		return charLiteral(t)
	case t[0] >= '0' && t[0] <= '9':
		t = strings.TrimRight(t, "uUlL")
		v, err := strconv.ParseUint(t, 0, 64)
		return int64(v), err
	default:
		if t == "sizeof" {
			return 0, fmt.Errorf("sizeof unsupported")
		}
		return p.ev.eval(t)
	}
}

func charLiteral(t string) (int64, error) {
	body := t[1 : len(t)-1]
	if body[0] != '\\' {
		return int64(body[0]), nil
	}
	switch body[1] {
	case 'n':
		return 10, nil
	case 't':
		return 9, nil
	case 'v':
		return 11, nil
	case 'f':
		return 12, nil
	case 'r':
		return 13, nil
	case 'b':
		return 8, nil
	case 'a':
		return 7, nil
	case '\\', '\'', '"':
		return int64(body[1]), nil
	case 'x':
		v, err := strconv.ParseUint(body[2:], 16, 32)
		return int64(v), err
	}
	v, err := strconv.ParseUint(body[1:], 8, 32)
	return int64(v), err
}
